// Packs the Aegis fortress designs into src/shared/fortresses.js (cells gzip + base64).
import { readFileSync, writeFileSync } from 'node:fs';
import { gzipSync } from 'node:zlib';
const blurb = {
  'Aegis Star Citadel': 'Star fort: 8 bastions, solid armoured core',
  'Aegis Star Citadel II': 'Hollow, three rings of guns, 6 open lanes',
  'Aegis Star Citadel III': 'Forward fan of 5 arms, carrier deck at the back',
  'Aegis Star Citadel IV': 'Giant harpoon, 44 plasma cannons, all guns forward',
};
const list = ['Aegis-Star-Citadel.json', 'Aegis-Star-Citadel-II.json', 'Aegis-Star-Citadel-III.json', 'Aegis-Star-Citadel-IV.json'].map((f) => {
  const o = JSON.parse(readFileSync(f, 'utf8'));
  return { name: o.name, blurb: blurb[o.name], w: o.w, h: o.h, hub: o.hub, gz: gzipSync(Buffer.from(o.cells, 'base64'), { level: 9 }).toString('base64') };
});
const out = `// Ready-made giant defences (owner, 12 Nov 2026: "put all 4 aegis in the defence designer in the
// start from menu so anyone can build them"). Designed by Claude with generator scripts in
// tools/fortress-gen/. Each is exactly 750,000 cr of blocks, so a 150,000 cr defence, with no
// thrusters; tools/test-designer.mjs checks they stay valid. The cells are gzipped + base64 to
// keep the page small (~${Math.round(list.reduce((s, f) => s + f.gz.length, 0) / 1000)} KB for all four); loadFortress() unpacks one on demand.
// Generated by tools/fortress-gen/pack.mjs: don't edit by hand.

export const FORTRESSES = ${JSON.stringify(list.map(({ gz, ...f }) => f), null, 2)};

const GZ = ${JSON.stringify(list.map((f) => f.gz))};

/** The k-th fortress as a design object (the same shape decodeDesign returns). */
export async function loadFortress(k) {
  const f = FORTRESSES[k], raw = Uint8Array.from(atob(GZ[k]), (c) => c.charCodeAt(0));
  const cells = new Uint8Array(await new Response(new Blob([raw]).stream().pipeThrough(new DecompressionStream('gzip'))).arrayBuffer());
  return { name: f.name, cls: 'worldbreaker', stance: 'line', place: 'auto', w: f.w, h: f.h, cells, hub: f.hub };
}
`;
writeFileSync(process.argv[2] || new URL('../../src/shared/fortresses.js', import.meta.url), out);
console.log('wrote', out.length, 'bytes');
